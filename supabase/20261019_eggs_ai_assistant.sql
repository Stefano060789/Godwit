alter table public.qr_campaigns
  add column if not exists ai_enabled boolean not null default false,
  add column if not exists ai_feedback_topics text[] not null
    default array['service', 'quality', 'speed', 'cleanliness', 'other'];

alter table public.qr_campaigns
  drop constraint if exists qr_campaigns_ai_feedback_topics_check;
alter table public.qr_campaigns
  add constraint qr_campaigns_ai_feedback_topics_check
  check (
    cardinality(ai_feedback_topics) between 1 and 7
    and ai_feedback_topics <@ array['service', 'quality', 'speed', 'cleanliness', 'atmosphere', 'value', 'other']::text[]
  );

create table if not exists public.egg_ai_sources (
  id bigint generated by default as identity primary key,
  campaign_id bigint not null references public.qr_campaigns(id) on delete cascade,
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  source_type text not null check (source_type in ('website', 'faq')),
  title text not null check (char_length(trim(title)) between 1 and 120),
  source_url text check (source_url is null or char_length(source_url) <= 500),
  content text not null check (char_length(trim(content)) between 1 and 8000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_egg_ai_sources_campaign
  on public.egg_ai_sources (campaign_id, created_at);

alter table public.egg_ai_sources enable row level security;

drop policy if exists "workspace managers manage Egg AI sources" on public.egg_ai_sources;
create policy "workspace managers manage Egg AI sources" on public.egg_ai_sources
for all to authenticated
using (public.is_workspace_manager(workspace_id))
with check (
  public.is_workspace_manager(workspace_id)
  and exists (
    select 1 from public.qr_campaigns campaign
    where campaign.id = public.egg_ai_sources.campaign_id
      and campaign.workspace_id = public.egg_ai_sources.workspace_id
  )
);
grant select, insert, delete on public.egg_ai_sources to authenticated;
grant usage, select on sequence public.egg_ai_sources_id_seq to authenticated;

create or replace function public.enforce_egg_ai_source_limit()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  target_workspace_id uuid;
  source_count integer;
begin
  select workspace_id into target_workspace_id
  from public.qr_campaigns
  where id = new.campaign_id;
  if target_workspace_id is null then raise exception 'The Egg does not exist.'; end if;
  new.workspace_id := target_workspace_id;

  perform pg_advisory_xact_lock(186753, hashtext(new.campaign_id::text));
  select count(*) into source_count
  from public.egg_ai_sources
  where campaign_id = new.campaign_id;
  if source_count >= 8 then
    raise exception 'An Egg can have at most 8 AI information sources.';
  end if;
  return new;
end;
$$;

drop trigger if exists trg_enforce_egg_ai_source_limit on public.egg_ai_sources;
create trigger trg_enforce_egg_ai_source_limit
before insert on public.egg_ai_sources
for each row execute function public.enforce_egg_ai_source_limit();

create table if not exists public.egg_ai_usage_counters (
  scope text not null check (scope in ('session', 'campaign', 'workspace', 'global')),
  scope_key text not null,
  period_start date not null,
  request_count integer not null default 0 check (request_count >= 0),
  primary key (scope, scope_key, period_start)
);

alter table public.egg_ai_usage_counters enable row level security;
revoke all on public.egg_ai_usage_counters from public, anon, authenticated;
grant all on public.egg_ai_usage_counters to service_role;

create or replace function public.reserve_egg_ai_turn(
  target_campaign_token text,
  target_session_hash text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  target_campaign_id bigint;
  target_workspace_id uuid;
  workspace_month date := date_trunc('month', now() at time zone 'utc')::date;
  today_utc date := (now() at time zone 'utc')::date;
  reserved_count integer;
begin
  if target_session_hash is null or target_session_hash !~ '^[a-f0-9]{64}$' then
    raise exception 'Invalid Egg AI session.';
  end if;

  select campaign.id, campaign.workspace_id
  into target_campaign_id, target_workspace_id
  from public.qr_campaigns campaign
  where campaign.token = target_campaign_token
    and campaign.is_active
    and campaign.ai_enabled
    and exists (
      select 1 from public.egg_ai_sources source
      where source.campaign_id = campaign.id
    );

  if target_campaign_id is null then
    raise exception 'Egg AI is not enabled for this Egg.';
  end if;

  insert into public.egg_ai_usage_counters (scope, scope_key, period_start, request_count)
  values ('session', target_campaign_id::text || ':' || target_session_hash, today_utc, 1)
  on conflict (scope, scope_key, period_start) do update
  set request_count = public.egg_ai_usage_counters.request_count + 1
  where public.egg_ai_usage_counters.request_count < 5
  returning request_count into reserved_count;
  if reserved_count is null then raise exception 'Egg AI usage limit reached for this session.'; end if;

  insert into public.egg_ai_usage_counters (scope, scope_key, period_start, request_count)
  values ('campaign', target_campaign_id::text, today_utc, 1)
  on conflict (scope, scope_key, period_start) do update
  set request_count = public.egg_ai_usage_counters.request_count + 1
  where public.egg_ai_usage_counters.request_count < 100
  returning request_count into reserved_count;
  if reserved_count is null then raise exception 'Egg AI daily usage limit reached.'; end if;

  insert into public.egg_ai_usage_counters (scope, scope_key, period_start, request_count)
  values ('workspace', target_workspace_id::text, workspace_month, 1)
  on conflict (scope, scope_key, period_start) do update
  set request_count = public.egg_ai_usage_counters.request_count + 1
  where public.egg_ai_usage_counters.request_count < 1000
  returning request_count into reserved_count;
  if reserved_count is null then raise exception 'Workspace Egg AI monthly usage limit reached.'; end if;

  insert into public.egg_ai_usage_counters (scope, scope_key, period_start, request_count)
  values ('global', 'godwit', today_utc, 1)
  on conflict (scope, scope_key, period_start) do update
  set request_count = public.egg_ai_usage_counters.request_count + 1
  where public.egg_ai_usage_counters.request_count < 5000
  returning request_count into reserved_count;
  if reserved_count is null then raise exception 'Godwit Egg AI daily usage limit reached.'; end if;
end;
$$;

revoke all on function public.reserve_egg_ai_turn(text, text) from public, anon, authenticated;
grant execute on function public.reserve_egg_ai_turn(text, text) to service_role;
