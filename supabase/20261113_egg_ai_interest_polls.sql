create table if not exists public.egg_ai_interest_polls (
  id bigint generated by default as identity primary key,
  campaign_id bigint not null references public.qr_campaigns(id) on delete cascade,
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  interest_key text not null check (interest_key ~ '^[a-z0-9][a-z0-9-]{0,39}$'),
  version integer not null check (version > 0),
  poll_id bigint not null references public.polls(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique (campaign_id, interest_key, version),
  unique (campaign_id, poll_id),
  unique (poll_id)
);

create index if not exists idx_egg_ai_interest_polls_campaign
  on public.egg_ai_interest_polls (campaign_id, interest_key, version desc);

create table if not exists public.egg_ai_interest_poll_sessions (
  campaign_id bigint not null,
  session_hash text not null check (session_hash ~ '^[0-9a-f]{64}$'),
  poll_id bigint not null,
  created_at timestamptz not null default now(),
  primary key (campaign_id, session_hash),
  foreign key (campaign_id, poll_id)
    references public.egg_ai_interest_polls(campaign_id, poll_id)
    on delete cascade
);

alter table public.egg_ai_interest_polls enable row level security;
alter table public.egg_ai_interest_poll_sessions enable row level security;
revoke all on public.egg_ai_interest_polls, public.egg_ai_interest_poll_sessions
  from public, anon, authenticated;
grant all on public.egg_ai_interest_polls, public.egg_ai_interest_poll_sessions
  to service_role;

create or replace function public.create_egg_ai_interest_poll(
  target_campaign_id bigint,
  target_session_hash text,
  target_interest_key text,
  target_question text,
  target_answers text[]
)
returns table(poll_id bigint, question text, answers jsonb, created boolean, reason text)
language plpgsql
security definer
set search_path = public
as $$
declare
  campaign_record public.qr_campaigns%rowtype;
  template_poll public.polls%rowtype;
  selected_poll public.polls%rowtype;
  existing_poll_id bigint;
  existing_interest_key text;
  workspace_owner_id uuid;
  next_version integer;
  allowed_polls integer;
begin
  if target_session_hash is null or target_session_hash !~ '^[0-9a-f]{64}$'
    or target_interest_key is null or target_interest_key !~ '^[a-z0-9][a-z0-9-]{0,39}$'
    or target_question is null or char_length(trim(target_question)) not between 1 and 250
    or coalesce(array_length(target_answers, 1), 0) not between 2 and 5
    or exists (
      select 1 from unnest(target_answers) as options(answer)
      where answer is null or char_length(trim(answer)) not between 1 and 80
    )
    or (select count(distinct lower(trim(answer))) from unnest(target_answers) as options(answer))
      <> array_length(target_answers, 1) then
    raise exception 'The customer-interest poll is invalid.';
  end if;

  select * into campaign_record
  from public.qr_campaigns
  where id = target_campaign_id
  for update;
  if not found or not campaign_record.is_active
    or not (campaign_record.ai_enabled
      or campaign_record.goal_key is not null
      or campaign_record.goal_keys is not null) then
    raise exception 'AI polls are not enabled for this active Egg.';
  end if;
  select owner_id into workspace_owner_id
  from public.workspaces
  where id = campaign_record.workspace_id;
  if workspace_owner_id is null then
    raise exception 'The Egg workspace owner could not be found.';
  end if;

  perform pg_advisory_xact_lock(186757, hashtext(campaign_record.workspace_id::text));
  perform pg_advisory_xact_lock(186758, hashtext(target_campaign_id::text));

  select interest_poll.interest_key, session_poll.poll_id
  into existing_interest_key, existing_poll_id
  from public.egg_ai_interest_poll_sessions session_poll
  join public.egg_ai_interest_polls interest_poll
    on interest_poll.campaign_id = session_poll.campaign_id
   and interest_poll.poll_id = session_poll.poll_id
  where session_poll.campaign_id = target_campaign_id
    and session_poll.session_hash = target_session_hash;
  if found then
    if existing_interest_key <> target_interest_key then
      return query select null::bigint, null::text, null::jsonb, false, 'session_limit'::text;
      return;
    end if;
    select * into selected_poll
    from public.polls
    where id = existing_poll_id;
    if found and coalesce(selected_poll.status, 'active') <> 'closed' and selected_poll.closed_at is null then
      return query select selected_poll.id, selected_poll.question, selected_poll.answers, false, null::text;
    else
      return query select null::bigint, null::text, null::jsonb, false, 'poll_closed'::text;
    end if;
    return;
  end if;

  select interest_poll.poll_id into existing_poll_id
  from public.egg_ai_interest_polls interest_poll
  join public.polls poll on poll.id = interest_poll.poll_id
  where interest_poll.campaign_id = target_campaign_id
    and interest_poll.interest_key = target_interest_key
    and coalesce(poll.status, 'active') <> 'closed'
    and poll.closed_at is null
  order by interest_poll.version desc
  limit 1;
  if found then
    insert into public.egg_ai_interest_poll_sessions (campaign_id, session_hash, poll_id)
    values (target_campaign_id, target_session_hash, existing_poll_id);
    select * into selected_poll from public.polls where id = existing_poll_id;
    return query select selected_poll.id, selected_poll.question, selected_poll.answers, false, null::text;
    return;
  end if;

  select coalesce(max(interest_poll.version), 0) + 1
  into next_version
  from public.egg_ai_interest_polls interest_poll
  where interest_poll.campaign_id = target_campaign_id
    and interest_poll.interest_key = target_interest_key;

  select limits.poll_limit into allowed_polls
  from public.workspace_plan_limits(campaign_record.workspace_id) limits;
  if (
    select count(*) from public.polls poll
    where poll.workspace_id = campaign_record.workspace_id
      and coalesce(poll.status, 'active') <> 'closed'
      and poll.closed_at is null
      and (poll.starts_at is null or poll.starts_at <= now())
      and (poll.ends_at is null or poll.ends_at > now())
  ) >= allowed_polls then
    return query select null::bigint, null::text, null::jsonb, false, 'poll_limit'::text;
    return;
  end if;

  select poll.* into template_poll
  from public.qr_campaign_items item
  join public.polls poll on poll.id = item.poll_id
  where item.campaign_id = target_campaign_id
    and item.workspace_id = campaign_record.workspace_id
    and item.item_type = 'poll'
    and poll.workspace_id = campaign_record.workspace_id
  order by item.sort_order asc nulls last, item.id
  limit 1;
  if not found and campaign_record.poll_id is not null then
    select * into template_poll
    from public.polls
    where id = campaign_record.poll_id
      and workspace_id = campaign_record.workspace_id;
  end if;
  insert into public.polls (
    workspace_id,
    creator_id,
    question,
    answers,
    multiple_choice,
    allow_user_answers,
    allow_organizer_messages,
    email_benefit_type,
    brand_name,
    brand_logo_url,
    brand_primary_color,
    brand_accent_color,
    review_benefit_type,
    review_trigger_answers,
    raffle_enabled
  )
  values (
    campaign_record.workspace_id,
    coalesce(template_poll.creator_id, workspace_owner_id),
    trim(target_question),
    to_jsonb(target_answers),
    false,
    false,
    false,
    'none',
    coalesce(template_poll.brand_name, campaign_record.name),
    template_poll.brand_logo_url,
    template_poll.brand_primary_color,
    template_poll.brand_accent_color,
    'none',
    '{}',
    false
  )
  returning * into selected_poll;

  insert into public.egg_ai_interest_polls (
    campaign_id, workspace_id, interest_key, version, poll_id
  )
  values (
    target_campaign_id, campaign_record.workspace_id, target_interest_key, next_version, selected_poll.id
  );
  insert into public.egg_ai_interest_poll_sessions (campaign_id, session_hash, poll_id)
  values (target_campaign_id, target_session_hash, selected_poll.id);

  return query select selected_poll.id, selected_poll.question, selected_poll.answers, true, null::text;
end;
$$;

revoke all on function public.create_egg_ai_interest_poll(bigint, text, text, text, text[])
  from public, anon, authenticated;
grant execute on function public.create_egg_ai_interest_poll(bigint, text, text, text, text[])
  to service_role;
