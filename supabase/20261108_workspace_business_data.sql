create or replace function public.get_public_qr_campaign(target_token text)
returns table(
  campaign_id bigint,
  poll_id bigint,
  portal_title text,
  portal_message text,
  portal_button_label text
)
language sql security definer set search_path = public stable as $$
  select id, poll_id, portal_title, portal_message, portal_button_label
  from public.qr_campaigns
  where token = target_token and is_active
  limit 1;
$$;
grant execute on function public.get_public_qr_campaign(text) to anon, authenticated;

create table if not exists public.workspace_ai_sources (
  id bigint generated by default as identity primary key,
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  source_type text not null check (source_type in ('website', 'notes', 'instagram')),
  title text not null check (char_length(trim(title)) between 1 and 120),
  source_url text check (source_url is null or char_length(source_url) <= 500),
  content text not null check (char_length(trim(content)) between 1 and 8000),
  created_at timestamptz not null default now(),
  check (source_type <> 'instagram' or
    (source_url is not null and source_url ~* '^https://(www\.)?instagram\.com/[a-z0-9._]+/?$'
     and content = source_url))
);

create index if not exists idx_workspace_ai_sources_workspace
  on public.workspace_ai_sources (workspace_id, created_at desc);
alter table public.workspace_ai_sources enable row level security;
drop policy if exists "workspace managers manage shared AI sources" on public.workspace_ai_sources;
create policy "workspace managers manage shared AI sources" on public.workspace_ai_sources
  for all to authenticated
  using (public.is_workspace_manager(workspace_id))
  with check (public.is_workspace_manager(workspace_id));
grant select, insert, delete on public.workspace_ai_sources to authenticated;
grant select on public.workspace_ai_sources to service_role;
grant usage, select on sequence public.workspace_ai_sources_id_seq to authenticated;

create or replace function public.enforce_workspace_ai_source_limit()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  perform pg_advisory_xact_lock(186754, hashtext(new.workspace_id::text));
  if (select count(*) from public.workspace_ai_sources where workspace_id = new.workspace_id) >= 8 then
    raise exception 'A workspace can have at most 8 shared AI information sources.';
  end if;
  return new;
end;
$$;
drop trigger if exists trg_enforce_workspace_ai_source_limit on public.workspace_ai_sources;
create trigger trg_enforce_workspace_ai_source_limit before insert on public.workspace_ai_sources
  for each row execute function public.enforce_workspace_ai_source_limit();

create or replace function public.reserve_egg_ai_turn(target_campaign_token text, target_session_hash text)
returns void language plpgsql security definer set search_path = public as $$
declare
  target_campaign_id bigint;
  target_workspace_id uuid;
  workspace_month date := date_trunc('month', now() at time zone 'utc')::date;
  today_utc date := (now() at time zone 'utc')::date;
  reserved_count integer;
begin
  if target_session_hash is null or target_session_hash !~ '^[a-f0-9]{64}$' then
    raise exception 'Invalid Egg AI session.';
  end if;
  select campaign.id, campaign.workspace_id into target_campaign_id, target_workspace_id
  from public.qr_campaigns campaign
  where campaign.token = target_campaign_token and campaign.is_active and campaign.ai_enabled
    and (exists (select 1 from public.egg_ai_sources source where source.campaign_id = campaign.id)
      or exists (select 1 from public.workspace_ai_sources source where source.workspace_id = campaign.workspace_id));
  if target_campaign_id is null then raise exception 'Egg AI is not enabled for this Egg.'; end if;

  insert into public.egg_ai_usage_counters (scope, scope_key, period_start, request_count)
  values ('session', target_campaign_id::text || ':' || target_session_hash, today_utc, 1)
  on conflict (scope, scope_key, period_start) do update
  set request_count = public.egg_ai_usage_counters.request_count + 1
  where public.egg_ai_usage_counters.request_count < 5 returning request_count into reserved_count;
  if reserved_count is null then raise exception 'Egg AI usage limit reached for this session.'; end if;

  insert into public.egg_ai_usage_counters (scope, scope_key, period_start, request_count)
  values ('campaign', target_campaign_id::text, today_utc, 1)
  on conflict (scope, scope_key, period_start) do update
  set request_count = public.egg_ai_usage_counters.request_count + 1
  where public.egg_ai_usage_counters.request_count < 100 returning request_count into reserved_count;
  if reserved_count is null then raise exception 'Egg AI daily usage limit reached.'; end if;

  insert into public.egg_ai_usage_counters (scope, scope_key, period_start, request_count)
  values ('workspace', target_workspace_id::text, workspace_month, 1)
  on conflict (scope, scope_key, period_start) do update
  set request_count = public.egg_ai_usage_counters.request_count + 1
  where public.egg_ai_usage_counters.request_count < 1000 returning request_count into reserved_count;
  if reserved_count is null then raise exception 'Workspace Egg AI monthly usage limit reached.'; end if;

  insert into public.egg_ai_usage_counters (scope, scope_key, period_start, request_count)
  values ('global', 'godwit', today_utc, 1)
  on conflict (scope, scope_key, period_start) do update
  set request_count = public.egg_ai_usage_counters.request_count + 1
  where public.egg_ai_usage_counters.request_count < 5000 returning request_count into reserved_count;
  if reserved_count is null then raise exception 'Godwit Egg AI daily usage limit reached.'; end if;
end;
$$;
revoke all on function public.reserve_egg_ai_turn(text, text) from public, anon, authenticated;
grant execute on function public.reserve_egg_ai_turn(text, text) to service_role;
