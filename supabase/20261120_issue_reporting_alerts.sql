create table if not exists public.issue_alert_settings (
  workspace_id uuid primary key references public.workspaces(id) on delete cascade,
  email_enabled boolean not null default false,
  sms_enabled boolean not null default false,
  in_app_enabled boolean not null default true,
  recipient_email text,
  recipient_phone text,
  updated_at timestamptz not null default now(),
  constraint issue_alert_settings_email_check
    check (recipient_email is null or (char_length(recipient_email) <= 320 and recipient_email ~* '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$')),
  constraint issue_alert_settings_phone_check
    check (recipient_phone is null or recipient_phone ~ '^\+[1-9][0-9]{7,14}$')
);

create table if not exists public.egg_issue_reports (
  id bigint generated by default as identity primary key,
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  campaign_id bigint not null references public.qr_campaigns(id) on delete cascade,
  category text not null check (category in ('service', 'cleanliness', 'accessibility', 'safety', 'other')),
  description text not null check (char_length(trim(description)) between 8 and 1000),
  reporter_session_id uuid not null,
  dispatch_token uuid not null default gen_random_uuid(),
  delivery_claimed_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists idx_egg_issue_reports_workspace_created
  on public.egg_issue_reports(workspace_id, created_at desc);
create index if not exists idx_egg_issue_reports_session_created
  on public.egg_issue_reports(campaign_id, reporter_session_id, created_at desc);

create table if not exists public.egg_issue_notifications (
  id bigint generated by default as identity primary key,
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  issue_id bigint not null unique references public.egg_issue_reports(id) on delete cascade,
  title text not null,
  message text not null,
  created_at timestamptz not null default now(),
  read_at timestamptz
);

create index if not exists idx_egg_issue_notifications_workspace_created
  on public.egg_issue_notifications(workspace_id, created_at desc);

alter table public.issue_alert_settings enable row level security;
alter table public.egg_issue_reports enable row level security;
alter table public.egg_issue_notifications enable row level security;

drop policy if exists "workspace managers manage issue alert settings" on public.issue_alert_settings;
create policy "workspace managers manage issue alert settings"
  on public.issue_alert_settings for all to authenticated
  using (public.is_workspace_manager(workspace_id))
  with check (public.is_workspace_manager(workspace_id));

