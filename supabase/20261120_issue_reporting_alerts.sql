  on public.egg_issue_notifications for update to authenticated
  using (public.is_workspace_manager(workspace_id))
  with check (public.is_workspace_manager(workspace_id));

create or replace function public.report_egg_issue(
  target_campaign_id bigint,
  issue_category text,
  issue_description text,
  target_session_id uuid
)
returns table(issue_id bigint, notification_token uuid)
language plpgsql
security definer
set search_path = public
as $$
declare
  target_workspace_id uuid;
  new_issue_id bigint;
  new_dispatch_token uuid;
  notification_enabled boolean;
begin
  if issue_category not in ('service', 'cleanliness', 'accessibility', 'safety', 'other') then
    raise exception 'Choose a valid issue category.';
  end if;
  if char_length(trim(coalesce(issue_description, ''))) not between 8 and 1000 then
    raise exception 'Describe the issue in 8 to 1000 characters.';
  end if;
  if target_session_id is null then
    raise exception 'A valid visitor session is required.';
  end if;

  select c.workspace_id into target_workspace_id
  from public.qr_campaigns c
  where c.id = target_campaign_id and c.is_active;
  if target_workspace_id is null then
    raise exception 'This Egg is not currently accepting issue reports.';
  end if;

  if exists (
    select 1 from public.egg_issue_reports r
    where r.campaign_id = target_campaign_id
      and r.reporter_session_id = target_session_id
      and r.created_at > now() - interval '5 minutes'
  ) then
    raise exception 'Please wait a few minutes before sending another issue report from this device.';
  end if;

  insert into public.egg_issue_reports (
    workspace_id, campaign_id, category, description, reporter_session_id
  )
  values (
    target_workspace_id, target_campaign_id, issue_category, trim(issue_description), target_session_id
  )
  returning id, dispatch_token into new_issue_id, new_dispatch_token;

  select coalesce(s.in_app_enabled, true) into notification_enabled
  from (select 1) seed
  left join public.issue_alert_settings s on s.workspace_id = target_workspace_id;

  if notification_enabled then
    insert into public.egg_issue_notifications (workspace_id, issue_id, title, message)
    values (
      target_workspace_id,
      new_issue_id,
      'New on-site issue report',
      upper(replace(issue_category, '_', ' ')) || ': ' || left(trim(issue_description), 500)
    );
  end if;

  return query select new_issue_id, new_dispatch_token;
end;
$$;

revoke all on function public.report_egg_issue(bigint, text, text, uuid) from public, authenticated;
grant execute on function public.report_egg_issue(bigint, text, text, uuid) to anon, authenticated;

create or replace function public.claim_egg_issue_alert_delivery(target_issue_id bigint, target_dispatch_token uuid)
returns table(
  issue_id bigint,
  workspace_name text,
  campaign_name text,
  category text,
  description text,
  in_app_enabled boolean,
  email_enabled boolean,
  sms_enabled boolean,
  recipient_email text,
  recipient_phone text
)
language plpgsql
security definer
set search_path = public
as $$
declare
  claimed_issue public.egg_issue_reports%rowtype;
begin
  update public.egg_issue_reports r
  set delivery_claimed_at = now()
  where r.id = target_issue_id
    and r.dispatch_token = target_dispatch_token
    and r.delivery_claimed_at is null
  returning r.* into claimed_issue;

  if claimed_issue.id is null then
    return;
  end if;

  return query
    select claimed_issue.id,
      w.name,
      c.name,
      claimed_issue.category,
      claimed_issue.description,
      coalesce(s.in_app_enabled, true),
      coalesce(s.email_enabled, false),
      coalesce(s.sms_enabled, false),
      s.recipient_email,
      s.recipient_phone
    from public.workspaces w
    join public.qr_campaigns c on c.id = claimed_issue.campaign_id
    left join public.issue_alert_settings s on s.workspace_id = claimed_issue.workspace_id
    where w.id = claimed_issue.workspace_id;
end;
$$;

revoke all on function public.claim_egg_issue_alert_delivery(bigint, uuid) from public, anon, authenticated;
grant execute on function public.claim_egg_issue_alert_delivery(bigint, uuid) to service_role;
