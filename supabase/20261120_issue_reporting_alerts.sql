create policy "workspace managers view Egg issue reports"
  on public.egg_issue_reports for select to authenticated
  using (public.is_workspace_manager(workspace_id));

drop policy if exists "workspace managers view issue notifications" on public.egg_issue_notifications;
create policy "workspace managers view issue notifications"
  on public.egg_issue_notifications for select to authenticated
  using (public.is_workspace_manager(workspace_id));

