after insert or update of adaptive_polls_enabled, goal_keys on public.qr_campaigns
for each row execute function public.track_adaptive_egg_campaign_setup();

create or replace function public.track_adaptive_egg_poll_item()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op <> 'INSERT' then
    perform public.sync_adaptive_egg_poll_setup(old.campaign_id);
  end if;
  if tg_op <> 'DELETE' then
    perform public.sync_adaptive_egg_poll_setup(new.campaign_id);
  end if;
  return null;
end;
$$;

