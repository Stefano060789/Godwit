create table if not exists public.egg_adaptive_poll_versions (
  id bigint generated by default as identity primary key,
  campaign_id bigint not null references public.qr_campaigns(id) on delete cascade,
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  version integer not null check (version between 1 and 3),
  poll_id bigint not null references public.polls(id) on delete restrict,
  observed_vote_count integer not null check (observed_vote_count >= 5),
  observed_message_count integer not null check (observed_message_count >= 0),
  created_at timestamptz not null default now(),
  unique (campaign_id, version),
  unique (poll_id)
);

create index if not exists idx_egg_adaptive_poll_versions_campaign
  on public.egg_adaptive_poll_versions (campaign_id, version desc);

create table if not exists public.egg_adaptive_poll_setups (
  campaign_id bigint primary key references public.qr_campaigns(id) on delete cascade,
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  setup_status text not null default 'pending' check (setup_status in ('pending', 'ready')),
  initial_poll_item_id bigint,
  initial_poll_id bigint,
  registered_at timestamptz,
  last_decision text,
  last_decided_at timestamptz,
  last_run_at timestamptz,
  next_run_at timestamptz,
  last_error text,
  updated_at timestamptz not null default now(),
  check (
    (setup_status = 'pending' and initial_poll_item_id is null and initial_poll_id is null and registered_at is null)
    or
    (setup_status = 'ready' and initial_poll_item_id is not null and initial_poll_id is not null and registered_at is not null)
  )
);

