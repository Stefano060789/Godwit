create or replace function public.sync_adaptive_egg_poll_setup(target_campaign_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  campaign_record public.qr_campaigns%rowtype;
  setup_record public.egg_adaptive_poll_setups%rowtype;
  poll_item_count integer;
  attached_item_id bigint;
  attached_poll_id bigint;
begin
  select * into campaign_record
  from public.qr_campaigns
  where id = target_campaign_id;
  if not found then return; end if;

  if not campaign_record.adaptive_polls_enabled or campaign_record.goal_keys is null then
    update public.egg_adaptive_poll_setups
    set setup_status = 'pending',
        initial_poll_item_id = null,
        initial_poll_id = null,
        registered_at = null,
        last_decision = case when campaign_record.adaptive_polls_enabled then 'setup_pending' else 'disabled' end,
        last_decided_at = now(),
        next_run_at = null,
        updated_at = now()
    where campaign_id = target_campaign_id;
    return;
  end if;

  insert into public.egg_adaptive_poll_setups (campaign_id, workspace_id)
  values (campaign_record.id, campaign_record.workspace_id)
  on conflict (campaign_id) do nothing;

  select * into setup_record
  from public.egg_adaptive_poll_setups
  where campaign_id = target_campaign_id
  for update;

  if setup_record.setup_status = 'ready' and exists (
    select 1
    from public.qr_campaign_items item
    where item.id = setup_record.initial_poll_item_id
      and item.campaign_id = target_campaign_id
  ) then
    return;
  end if;

  update public.egg_adaptive_poll_setups
  set setup_status = 'pending',
      initial_poll_item_id = null,
      initial_poll_id = null,
      registered_at = null,
      last_decision = 'setup_pending',
      last_decided_at = now(),
      next_run_at = null,
      updated_at = now()
  where campaign_id = target_campaign_id
    and setup_status <> 'pending';

  select count(*), min(item.id), min(item.poll_id)
  into poll_item_count, attached_item_id, attached_poll_id
  from public.qr_campaign_items item
  where item.campaign_id = target_campaign_id
    and item.item_type = 'poll';
  if poll_item_count <> 1 then return; end if;
  if not exists (
    select 1
    from public.polls poll
    where poll.id = attached_poll_id
      and poll.workspace_id = campaign_record.workspace_id
  ) then
    return;
  end if;

  update public.egg_adaptive_poll_setups
  set setup_status = 'ready',
      initial_poll_item_id = attached_item_id,
      initial_poll_id = attached_poll_id,
      registered_at = now(),
      last_decision = 'enrolled',
      last_decided_at = now(),
      last_run_at = null,
      next_run_at = now() + interval '30 days',
      last_error = null,
      updated_at = now()
  where campaign_id = target_campaign_id;
end;
$$;

create or replace function public.track_adaptive_egg_campaign_setup()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  perform public.sync_adaptive_egg_poll_setup(new.id);
  return new;
end;
$$;

