create or replace function public.publish_adaptive_egg_poll(
  target_campaign_id bigint,
  expected_poll_id bigint,
  target_question text,
  target_answers text[],
  observed_vote_count integer,
  observed_message_count integer
)
returns table(poll_id bigint, version integer)
language plpgsql
security definer
set search_path = public
as $$
declare
  campaign_record public.qr_campaigns%rowtype;
  prior_poll public.polls%rowtype;
  poll_item_id bigint;
  current_item_poll_id bigint;
  poll_item_count integer;
  next_version integer;
  new_poll_id bigint;
begin
  perform pg_advisory_xact_lock(186755, hashtext(target_campaign_id::text));

  select * into campaign_record
  from public.qr_campaigns
  where id = target_campaign_id
  for update;
  if not found or not campaign_record.is_active or not campaign_record.adaptive_polls_enabled then
    raise exception 'Adaptive polling is not enabled for this active Egg.';
  end if;
  if campaign_record.created_at > now() - interval '30 days' then
    raise exception 'This Egg is not old enough for adaptive polling.';
  end if;
  if observed_vote_count < 5 or observed_message_count < 0 then
    raise exception 'Adaptive polling requires at least five recent votes and valid message counts.';
  end if;
  if target_question is null or char_length(trim(target_question)) not between 1 and 250
    or coalesce(array_length(target_answers, 1), 0) not between 2 and 5
    or exists (
      select 1 from unnest(target_answers) as options(answer)
      where answer is null or char_length(trim(answer)) not between 1 and 80
    )
    or (select count(distinct lower(trim(answer))) from unnest(target_answers) as options(answer))
      <> array_length(target_answers, 1) then
    raise exception 'The adaptive poll question or answers are invalid.';
  end if;

  select count(*) into poll_item_count
  from public.qr_campaign_items
  where campaign_id = target_campaign_id and item_type = 'poll';
  if poll_item_count <> 1 then
    raise exception 'Adaptive polling only replaces the single managed poll item.';
  end if;
  select id, poll_id into poll_item_id, current_item_poll_id
  from public.qr_campaign_items
  where campaign_id = target_campaign_id and item_type = 'poll'
  for update;
  if current_item_poll_id is distinct from expected_poll_id then
    raise exception 'The Egg poll changed while an adaptive poll was being generated.';
  end if;

  select * into prior_poll
  from public.polls
  where id = current_item_poll_id
    and workspace_id = campaign_record.workspace_id
  for update;
  if not found or prior_poll.status = 'closed' then
    raise exception 'The current Egg poll is unavailable or closed.';
  end if;

  select coalesce(max(egg_adaptive_poll_versions.version), 0) + 1
  into next_version
  from public.egg_adaptive_poll_versions
  where campaign_id = target_campaign_id;
  if next_version > 3 then
    raise exception 'This Egg has reached its adaptive poll version limit.';
  end if;
  if exists (
    select 1 from public.egg_adaptive_poll_versions
    where campaign_id = target_campaign_id
      and created_at > now() - interval '30 days'
  ) then
    raise exception 'This Egg was adapted less than 30 days ago.';
  end if;

  insert into public.polls (
    workspace_id,
    creator_id,
    question,
    answers,
    multiple_choice,
    allow_user_answers,
    allow_organizer_messages,
    email_benefit_type,
    email_benefit_value,
    email_benefit_url,
    brand_name,
    brand_logo_url,
    brand_primary_color,
    brand_accent_color,
    review_benefit_type,
    review_benefit_value,
    review_benefit_url,
    review_trigger_answers,
    raffle_enabled
  )
  values (
    prior_poll.workspace_id,
    prior_poll.creator_id,
    trim(target_question),
    to_jsonb(target_answers),
    false,
    coalesce(prior_poll.allow_user_answers, false),
    coalesce(prior_poll.allow_organizer_messages, false),
    coalesce(prior_poll.email_benefit_type, 'none'),
    prior_poll.email_benefit_value,
    prior_poll.email_benefit_url,
    prior_poll.brand_name,
    prior_poll.brand_logo_url,
    prior_poll.brand_primary_color,
    prior_poll.brand_accent_color,
    'none',
    null,
    null,
    '{}',
    false
  )
  returning id into new_poll_id;

  update public.qr_campaign_items
  set poll_id = new_poll_id
  where id = poll_item_id;
  update public.qr_campaigns
  set poll_id = new_poll_id, updated_at = now()
  where id = target_campaign_id;

  insert into public.egg_adaptive_poll_versions (
    campaign_id,
    workspace_id,
    version,
    poll_id,
    observed_vote_count,
    observed_message_count
  )
  values (
    target_campaign_id,
    campaign_record.workspace_id,
    next_version,
    new_poll_id,
    observed_vote_count,
    observed_message_count
  );

  update public.egg_adaptive_poll_setups
  set last_decision = 'adapted',
      last_decided_at = now(),
      last_run_at = now(),
      next_run_at = now() + interval '30 days',
      last_error = null,
      updated_at = now()
  where campaign_id = target_campaign_id
    and setup_status = 'ready';

  return query select new_poll_id, next_version;
end;
$$;

