create or replace function public.set_egg_adaptive_polling(
  target_campaign_id bigint,
  enable_adaptive_polling boolean
)
returns table(campaign_id bigint, adaptive_polls_enabled boolean, setup_status text, next_run_at timestamptz)
language plpgsql
security definer
set search_path = public
as $$
declare
  campaign_record public.qr_campaigns%rowtype;
  poll_item_count integer;
begin
  select * into campaign_record
  from public.qr_campaigns
  where id = target_campaign_id
  for update;
  if not found or not public.is_workspace_manager(campaign_record.workspace_id) then
    raise exception 'You do not have permission to manage adaptive polling for this Egg.';
  end if;

  if enable_adaptive_polling then
    if not campaign_record.is_active
      or campaign_record.business_type is null
      or (campaign_record.goal_keys is null and campaign_record.goal_key is null) then
      raise exception 'Only an active goal-based Egg can enable adaptive polling.';
    end if;

    select count(*) into poll_item_count
    from public.qr_campaign_items item
    where item.campaign_id = target_campaign_id
      and item.workspace_id = campaign_record.workspace_id
      and item.item_type = 'poll';
    if poll_item_count <> 1 or not exists (
      select 1
      from public.qr_campaign_items item
      join public.polls poll on poll.id = item.poll_id
      where item.campaign_id = target_campaign_id
        and item.workspace_id = campaign_record.workspace_id
        and item.item_type = 'poll'
        and poll.workspace_id = campaign_record.workspace_id
        and poll.status is distinct from 'closed'
    ) then
      raise exception 'Adaptive polling requires exactly one open poll attached to this Egg.';
    end if;
  end if;

  update public.qr_campaigns
  set adaptive_polls_enabled = enable_adaptive_polling,
      updated_at = now()
  where id = target_campaign_id;

  perform public.sync_adaptive_egg_poll_setup(target_campaign_id);

  return query
  select campaign_record.id,
         campaign.adaptive_polls_enabled,
         setup.setup_status,
         setup.next_run_at
  from public.qr_campaigns campaign
  left join public.egg_adaptive_poll_setups setup on setup.campaign_id = campaign.id
  where campaign.id = target_campaign_id;
end;
$$;

create or replace function public.get_workspace_adaptive_poll_status()
returns table(
  campaign_id bigint,
  campaign_name text,
  adaptive_polls_enabled boolean,
  setup_status text,
  last_decision text,
  last_decided_at timestamptz,
  last_run_at timestamptz,
  next_run_at timestamptz,
  last_error text,
  current_poll_id bigint,
  adaptive_version integer
)
language sql
security definer
set search_path = public
stable
as $$
  select campaign.id,
         campaign.name,
         campaign.adaptive_polls_enabled,
         setup.setup_status,
         setup.last_decision,
         setup.last_decided_at,
         setup.last_run_at,
         setup.next_run_at,
         setup.last_error,
         item.poll_id,
         coalesce((
           select max(adaptive_version.version)
           from public.egg_adaptive_poll_versions adaptive_version
           where adaptive_version.campaign_id = campaign.id
         ), 0)::integer
  from public.qr_campaigns campaign
  left join public.egg_adaptive_poll_setups setup on setup.campaign_id = campaign.id
  left join lateral (
    select campaign_item.poll_id
    from public.qr_campaign_items campaign_item
    where campaign_item.campaign_id = campaign.id and campaign_item.item_type = 'poll'
    order by campaign_item.id
    limit 1
  ) item on true
  where campaign.workspace_id = public.current_workspace_id()
    and public.is_workspace_manager(campaign.workspace_id)
    and (campaign.goal_keys is not null or campaign.goal_key is not null);
$$;

create or replace function public.set_goal_egg_email_benefit(
  target_campaign_id bigint,
  benefit_type text,
  benefit_value text,
  benefit_url text
)
returns table(campaign_id bigint, poll_id bigint, email_benefit_type text, email_benefit_value text, email_benefit_url text)
language plpgsql
security definer
set search_path = public
as $$
declare
  campaign_record public.qr_campaigns%rowtype;
  managed_poll_id bigint;
  normalized_type text := coalesce(nullif(trim(benefit_type), ''), 'none');
  normalized_value text := nullif(trim(coalesce(benefit_value, '')), '');
  normalized_url text := nullif(trim(coalesce(benefit_url, '')), '');
begin
  select * into campaign_record
  from public.qr_campaigns
  where id = target_campaign_id
  for update;
  if not found or not public.is_workspace_manager(campaign_record.workspace_id) then
    raise exception 'You do not have permission to manage this Egg benefit.';
  end if;
  if not campaign_record.adaptive_polls_enabled
    or (campaign_record.goal_keys is null and campaign_record.goal_key is null) then
    raise exception 'Customer benefits can only be updated on a goal-managed Egg.';
  end if;

  if normalized_type not in ('none', 'voucher', 'discount_code') then
    raise exception 'Choose a valid customer benefit.';
  end if;
  if normalized_type = 'none' then
    normalized_value := null;
    normalized_url := null;
  elsif (normalized_value is null and normalized_url is null)
    or char_length(coalesce(normalized_value, '')) > 200
    or char_length(coalesce(normalized_url, '')) > 500 then
    raise exception 'Enter a voucher, discount code, or redemption link.';
  end if;
  if normalized_url is not null
    and normalized_url !~* '^https://[a-z0-9.-]+(:[0-9]{1,5})?([/?#][^[:space:]@]*)?$' then
    raise exception 'Use a valid HTTPS redemption link without credentials.';
  end if;
  if normalized_type <> 'none' and public.workspace_plan(campaign_record.workspace_id) = 'free' then
    raise exception 'Email-sharing benefits are available on the Starter plan and above.';
  end if;

  if (
    select count(*)
    from public.qr_campaign_items item
    where item.campaign_id = target_campaign_id
      and item.workspace_id = campaign_record.workspace_id
      and item.item_type = 'poll'
  ) <> 1 then
    raise exception 'This Egg must have exactly one managed poll.';
  end if;

  select item.poll_id into managed_poll_id
  from public.qr_campaign_items item
  join public.polls poll on poll.id = item.poll_id
  where item.campaign_id = target_campaign_id
    and item.workspace_id = campaign_record.workspace_id
    and item.item_type = 'poll'
    and poll.workspace_id = campaign_record.workspace_id
    and poll.status is distinct from 'closed'
  for update of poll;
  if managed_poll_id is null then
    raise exception 'The managed poll is unavailable or closed.';
  end if;

  update public.polls
  set email_benefit_type = normalized_type,
      email_benefit_value = normalized_value,
      email_benefit_url = normalized_url
  where id = managed_poll_id
    and workspace_id = campaign_record.workspace_id;

  return query
  select target_campaign_id, poll.id, poll.email_benefit_type, poll.email_benefit_value, poll.email_benefit_url
  from public.polls poll
  where poll.id = managed_poll_id;
end;
$$;

create or replace function public.record_adaptive_poll_decision(
  target_campaign_id bigint,
  decision text,
  next_run_at timestamptz,
  error_message text default null
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if decision not in (
    'cooldown',
    'insufficient_responses',
    'poll_limit',
    'poll_missing',
    'setup_pending',
    'generation_failed',
    'disabled',
    'version_limit'
  ) then
    raise exception 'Invalid adaptive poll decision.';
  end if;
  if error_message is not null and char_length(error_message) > 500 then
    raise exception 'Adaptive poll error summary is too long.';
  end if;

  update public.egg_adaptive_poll_setups
  set last_decision = decision,
      last_decided_at = now(),
      last_run_at = now(),
      next_run_at = case
        when decision in ('disabled', 'version_limit') then null
        else coalesce(next_run_at, now() + interval '7 days')
      end,
      last_error = error_message,
      updated_at = now()
  where campaign_id = target_campaign_id
    and setup_status = 'ready';
end;
$$;

