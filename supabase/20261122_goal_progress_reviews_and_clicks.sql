create table if not exists public.egg_review_feedback (
  id bigint generated by default as identity primary key,
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  campaign_id bigint not null references public.qr_campaigns(id) on delete cascade,
  reporter_session_id uuid not null,
  feedback text not null check (char_length(trim(feedback)) between 10 and 1200),
  created_at timestamptz not null default now(),
  unique (campaign_id, reporter_session_id)
);

create index if not exists idx_egg_review_feedback_workspace_created
  on public.egg_review_feedback(workspace_id, created_at desc);

alter table public.egg_review_feedback enable row level security;

drop policy if exists "workspace managers view Egg review feedback" on public.egg_review_feedback;
create policy "workspace managers view Egg review feedback"
  on public.egg_review_feedback for select to authenticated
  using (public.is_workspace_manager(workspace_id));

revoke all on public.egg_review_feedback from anon, authenticated;
grant select on public.egg_review_feedback to authenticated;

create or replace function public.submit_egg_review_feedback(
  target_campaign_id bigint,
  target_session_id uuid,
  review_feedback text
)
returns boolean
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  target_workspace_id uuid;
  inserted_id bigint;
begin
  if target_session_id is null then
    raise exception 'A valid visitor session is required.';
  end if;
  if char_length(trim(coalesce(review_feedback, ''))) not between 10 and 1200 then
    raise exception 'Feedback must be between 10 and 1200 characters.';
  end if;

  select campaign.workspace_id into target_workspace_id
  from public.qr_campaigns campaign
  where campaign.id = target_campaign_id
    and campaign.is_active
    and coalesce(campaign.goal_keys, array[campaign.goal_key]) && array['reviews']::text[];

  if target_workspace_id is null then
    raise exception 'This Egg is not available for review feedback.';
  end if;

  insert into public.egg_review_feedback (
    workspace_id, campaign_id, reporter_session_id, feedback
  ) values (
    target_workspace_id, target_campaign_id, target_session_id, trim(review_feedback)
  )
  on conflict (campaign_id, reporter_session_id) do nothing
  returning id into inserted_id;

  return inserted_id is not null;
end;
$$;

revoke all on function public.submit_egg_review_feedback(bigint, uuid, text) from public;
grant execute on function public.submit_egg_review_feedback(bigint, uuid, text) to anon, authenticated;

