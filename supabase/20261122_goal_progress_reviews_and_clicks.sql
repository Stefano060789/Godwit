  on public.egg_promotion_link_clicks(campaign_id, created_at desc);

alter table public.egg_promotion_link_clicks enable row level security;
revoke all on public.egg_promotion_link_clicks from public, anon, authenticated;

create or replace function public.record_egg_promotion_link_click(
  target_campaign_id bigint,
  target_item_id bigint,
  target_session_id uuid
)
returns boolean
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  target_is_promotion boolean;
begin
  if target_session_id is null then
    raise exception 'A valid visitor session is required.';
  end if;

  select campaign.is_active
    and coalesce(campaign.goal_keys, array[campaign.goal_key]) && array['promotion']::text[]
    and item.campaign_id = campaign.id
    and item.item_type in ('info', 'reward')
    and item.link_url is not null
  into target_is_promotion
  from public.qr_campaigns campaign
  join public.qr_campaign_items item on item.id = target_item_id
  where campaign.id = target_campaign_id;

  if target_is_promotion is distinct from true then
    return false;
  end if;

  insert into public.egg_promotion_link_clicks (
    campaign_id, item_id, visitor_session_id
  ) values (
    target_campaign_id, target_item_id, target_session_id
  )
  on conflict (campaign_id, item_id, visitor_session_id) do nothing;

  return found;
end;
$$;

revoke all on function public.record_egg_promotion_link_click(bigint, bigint, uuid) from public;
grant execute on function public.record_egg_promotion_link_click(bigint, bigint, uuid) to anon, authenticated;

create or replace function public.get_workspace_primary_goal_progress()
returns table(
  campaign_id bigint,
  activity_date date,
  metric text,
  event_count bigint
)
language sql
security definer
set search_path = public, pg_temp
volatile
as $$
  with workspace_campaigns as (
    select id
    from public.qr_campaigns
    where workspace_id = public.current_workspace_id()
  )
  select event.campaign_id, event.created_at::date, 'help_interactions'::text, count(*)::bigint
  from public.qr_scan_events event
  join workspace_campaigns campaign on campaign.id = event.campaign_id
  where event.created_at >= now() - interval '30 days'
  group by event.campaign_id, event.created_at::date

  union all

  select vote.campaign_id, vote.created_at::date, 'responses'::text, count(*)::bigint
  from public.votes vote
  join workspace_campaigns campaign on campaign.id = vote.campaign_id
  where vote.created_at >= now() - interval '30 days'
  group by vote.campaign_id, vote.created_at::date

  union all

  select lead.campaign_id, lead.created_at::date, 'contacts'::text, count(*)::bigint
  from public.voter_leads lead
  join workspace_campaigns campaign on campaign.id = lead.campaign_id
  where lead.created_at >= now() - interval '30 days'
  group by lead.campaign_id, lead.created_at::date

  union all

  select report.campaign_id, report.created_at::date, 'issues'::text, count(*)::bigint
  from public.egg_issue_reports report
  join workspace_campaigns campaign on campaign.id = report.campaign_id
  where report.created_at >= now() - interval '30 days'
  group by report.campaign_id, report.created_at::date

  union all

  select review.campaign_id, review.created_at::date, 'private_reviews'::text, count(*)::bigint
  from public.egg_review_feedback review
  join workspace_campaigns campaign on campaign.id = review.campaign_id
  where review.created_at >= now() - interval '30 days'
  group by review.campaign_id, review.created_at::date

  union all

  select click.campaign_id, click.created_at::date, 'promotion_clicks'::text, count(*)::bigint
  from public.egg_promotion_link_clicks click
  join workspace_campaigns campaign on campaign.id = click.campaign_id
  where click.created_at >= now() - interval '30 days'
  group by click.campaign_id, click.created_at::date;
$$;

revoke all on function public.get_workspace_primary_goal_progress() from public, anon;
grant execute on function public.get_workspace_primary_goal_progress() to authenticated;
