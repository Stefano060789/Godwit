import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { pathToFileURL } from "node:url";
const { PGlite } = await import(process.env.PGLITE_MODULE
  ? pathToFileURL(process.env.PGLITE_MODULE).href
  : "../.billing-sql-tools/node_modules/@electric-sql/pglite/dist/index.js");
const db = new PGlite();
const workspace = "11111111-1111-4111-8111-111111111111";
const otherWorkspace = "22222222-2222-4222-8222-222222222222";
const session = "a".repeat(64);
let checks = 0;
const check = (actual, expected) => { assert.deepEqual(actual, expected); checks++; };
const row = async (sql) => (await db.query(sql)).rows[0];
const poll = async (topic, multiple = true, hash = session) => row(
  `select * from public.create_egg_ai_interest_poll(1,'${hash}','${topic}','Choose ${topic}',array['One','Two','Three'],${multiple})`
);
try {
  await db.exec(`
    create role anon; create role authenticated; create role service_role bypassrls;
    create table public.workspaces(id uuid primary key,owner_id uuid);
    create table public.qr_campaigns(id bigint primary key,workspace_id uuid,name text,is_active boolean,
      ai_enabled boolean,goal_key text,goal_keys text[],poll_id bigint);
    create table public.polls(id bigint generated by default as identity primary key,
      workspace_id uuid,creator_id uuid,question text,answers jsonb,multiple_choice boolean,
      allow_user_answers boolean,allow_organizer_messages boolean,email_benefit_type text,
      brand_name text,brand_logo_url text,brand_primary_color text,brand_accent_color text,
      review_benefit_type text,review_trigger_answers text[],raffle_enabled boolean,
      status text default 'active',closed_at timestamptz,starts_at timestamptz,ends_at timestamptz);
    create table public.qr_campaign_items(id bigint,workspace_id uuid,campaign_id bigint,item_type text,poll_id bigint,sort_order integer);
    create table public.plan_caps(workspace_id uuid,poll_limit integer);
    create function public.workspace_plan_limits(w uuid) returns table(poll_limit integer)
      language sql security definer set search_path = '' as $$select p.poll_limit from public.plan_caps p where workspace_id=w$$;
    insert into public.workspaces values ('${workspace}','${workspace}'),('${otherWorkspace}','${otherWorkspace}');
    insert into public.qr_campaigns values (1,'${workspace}','Cafe',true,true,null,null,null);
    insert into public.plan_caps values ('${workspace}',20);
  `);
  for (const name of ["20261113_egg_ai_interest_polls.sql", "20261125_multi_choice_egg_ai_polls.sql"]) {
    await db.exec(await readFile(new URL(`../supabase/${name}`, import.meta.url), "utf8"));
  }
  await db.exec("set role service_role");
  const first = await poll("menu");
  check(first.created, true);
  check(first.multiple_choice, true);
  check((await row(`select multiple_choice,allow_user_answers,allow_organizer_messages,email_benefit_type,review_benefit_type,raffle_enabled from public.polls where id=${first.poll_id}`)),
    { multiple_choice: true, allow_user_answers: false, allow_organizer_messages: false, email_benefit_type: "none", review_benefit_type: "none", raffle_enabled: false });
  check((await poll("events", false)).multiple_choice, false);
  check((await poll("visit")).created, true);
  check((await poll("fourth")).reason, "session_limit");
  check((await poll("menu")).poll_id, first.poll_id);
  check((await poll("menu", true, "b".repeat(64))).created, false);
  check((await row("select count(*)::integer as count from public.polls")).count, 3);
  const single = await poll("menu", false, "c".repeat(64));
  check(single.multiple_choice, false);
  assert.notEqual(single.poll_id, first.poll_id); checks++;
  check((await row("select bool_and(retention_expires_at = created_at + interval '30 days') as ok from public.egg_ai_interest_poll_sessions")).ok, true);
  await db.exec("reset role; update public.plan_caps set poll_limit=4; set role service_role");
  check((await poll("capped", true, "d".repeat(64))).reason, "poll_limit");

  for (const user of [workspace, otherWorkspace]) {
    await db.exec(`reset role; set role authenticated; set request.jwt.claims='{"sub":"${user}","role":"authenticated"}'`);
    for (const sql of [
      "select 1 from public.egg_ai_interest_poll_sessions",
      "update public.egg_ai_interest_poll_sessions set session_hash=repeat('f',64) returning 1",
      "delete from public.egg_ai_interest_poll_sessions returning 1",
      `insert into public.egg_ai_interest_poll_sessions(campaign_id,session_hash,poll_id) values(1,repeat('f',64),${first.poll_id})`,
      `select * from public.create_egg_ai_interest_poll(1,repeat('f',64),'forged','Question',array['One','Two'],true)`
    ]) { await assert.rejects(() => db.exec(sql), /permission denied/); checks++; }
  }
  await db.exec("reset role; set role anon");
  await assert.rejects(() => db.exec("select 1 from public.egg_ai_interest_poll_sessions"), /permission denied/); checks++;
  await db.exec("reset role");
  for (const operation of ["select", "update", "delete"]) {
    await db.exec(`grant ${operation} on public.egg_ai_interest_poll_sessions to authenticated;
      create policy tmp_open on public.egg_ai_interest_poll_sessions for ${operation} to authenticated using (true);
      set role authenticated;`);
    const probe = operation === "select" ? "select 1 from public.egg_ai_interest_poll_sessions"
      : operation === "update" ? "update public.egg_ai_interest_poll_sessions set retention_expires_at=now()+interval '31 days' returning 1"
        : "delete from public.egg_ai_interest_poll_sessions returning 1";
    await assert.rejects(() => assert.rejects(() => db.exec(probe), /permission denied/), { name: "AssertionError" }); checks++;
    await db.exec(`reset role; drop policy tmp_open on public.egg_ai_interest_poll_sessions;
      revoke ${operation} on public.egg_ai_interest_poll_sessions from authenticated;`);
  }
  console.log(`AI multi-poll SQL: ${checks} checks passed.`);
} finally { await db.close(); }
